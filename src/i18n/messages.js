/** @type {string} */
let locale = 'es';

/**
 * Selects the language used by menu strings.
 * @param {string} next Locale code.
 * @returns {void}
 */
export function setEditorLocale(next) {
  locale = messages[next] ? next : 'es';
}

/**
 * @param {string} key Message key.
 * @param {Record<string, string|number>} [params] Values for {name} placeholders.
 * @returns {string} Text for the active locale.
 */
export function t(key, params) {
  const table = messages[locale] ?? messages.es;
  const template = table[key] ?? messages.es[key] ?? key;
  if (!params) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''));
}
